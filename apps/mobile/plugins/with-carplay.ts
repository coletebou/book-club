import fs from 'node:fs';
import path from 'node:path';
import { type ConfigPlugin, IOSConfig, withDangerousMod, withEntitlementsPlist, withInfoPlist, withPodfileProperties, withXcodeProject } from 'expo/config-plugins';

export interface CarPlayProps {
  /** STORE_TARGETS.carplay, or BOOKCLUB_CARPLAY=1 (D221): off, a build signs with a profile that lacks the entitlement. */
  readonly enabled: boolean;
}

export const CARPLAY_ENTITLEMENT = 'com.apple.developer.carplay-audio';
export const CARPLAY_ROLE = 'CPTemplateApplicationSceneSessionRoleApplication';
export const CARPLAY_SCENE_DELEGATE = 'BookClubCarPlaySceneDelegate';
const DELEGATE_FILE = `${CARPLAY_SCENE_DELEGATE}.swift`;

type Plist = Record<string, unknown>;

/**
 * The Info.plist with CarPlay's scene beside the phone's (D221). Expo's own template already makes
 * the app scene-based (its SceneDelegate, required by the iOS 27 SDK): the car is one more role,
 * its own delegate, and the phone's scene configuration is left exactly as it was. Fails loudly
 * without that manifest rather than make one up.
 *
 * `UIApplicationSupportsMultipleScenes` becomes true (D232): the car's screen is a second scene of
 * the app beside the phone's, Apple documents that with it false "UIKit never creates more than one
 * scene for your app", and its CarPlay guide's own manifest sets it. An iPad or a folding iPhone
 * then offers a second window of the app, which `withOneWindow` closes.
 */
export function withCarPlayScene(plist: Plist): Plist {
  const manifest = plist.UIApplicationSceneManifest as { UISceneConfigurations?: Record<string, unknown[]> } | undefined;
  if (!manifest?.UISceneConfigurations) throw new Error('withCarPlay: the Info.plist has no UIApplicationSceneManifest; the app must be scene-based (Expo SDK 58)');
  const configuration = { UISceneClassName: 'CPTemplateApplicationScene', UISceneConfigurationName: 'CarPlay', UISceneDelegateClassName: CARPLAY_SCENE_DELEGATE };
  return {
    ...plist,
    UIApplicationSceneManifest: { ...manifest, UIApplicationSupportsMultipleScenes: true, UISceneConfigurations: { ...manifest.UISceneConfigurations, [CARPLAY_ROLE]: [configuration] } },
  };
}

/** Where Expo's template leaves room in the phone's scene delegate (its SceneDelegate.swift). */
const SCENE_DELEGATE_ANCHOR = '  // Extension point for config plugins.\n';
const ONE_WINDOW_MARK = '// One window (D232, plugins/with-carplay.ts)';

/**
 * The phone's scene delegate, keeping the app to one window (D232). With multiple scenes on for the
 * car, an iPad or a folding iPhone can ask for a second window of the app; it has one page and one
 * player, so a second window's session is closed as it opens, before React Native starts in it.
 * Fails loudly when the template's delegate is not the one this was written against.
 */
export function withOneWindow(sceneDelegate: string): string {
  const override = [
    `  ${ONE_WINDOW_MARK}: CarPlay needs UIApplicationSupportsMultipleScenes, and with it an`,
    '  // iPad or a folding iPhone offers a second window of the app. The app has one page and one player,',
    '  // so a second window is closed as it opens, before React Native starts in it; a link it was',
    '  // opened for goes to the window there is, which comes to the front.',
    '  override func scene(_ scene: UIScene, willConnectTo session: UISceneSession, options connectionOptions: UIScene.ConnectionOptions) {',
    '    BookClubReactStartup.shared.prepare(window: true) { [weak self] in',
    '      self?.connectWindow(scene, session: session, options: connectionOptions)',
    '    }',
    '  }',
    '',
    '  private func connectWindow(_ scene: UIScene, session: UISceneSession, options connectionOptions: UIScene.ConnectionOptions) {',
    '    let existing = UIApplication.shared.connectedScenes.first { other in',
    '      other !== scene && other.session.role == .windowApplication && (other.delegate as? SceneDelegate)?.window != nil',
    '    }',
    '    if let existing {',
    '      if !connectionOptions.urlContexts.isEmpty {',
    '        (existing.delegate as? SceneDelegate)?.scene(existing, openURLContexts: connectionOptions.urlContexts)',
    '      }',
    '      UIApplication.shared.requestSceneSessionActivation(existing.session, userActivity: nil, options: nil, errorHandler: nil)',
    '      UIApplication.shared.requestSceneSessionDestruction(session, options: nil, errorHandler: nil)',
    '      return',
    '    }',
    '    super.scene(scene, willConnectTo: session, options: connectionOptions)',
    '  }',
    '',
  ].join('\n');
  if (sceneDelegate.includes(ONE_WINDOW_MARK)) {
    // A second prebuild over the same ios/. One made by an older version of this plugin is not
    // rewritten in place: say so, instead of building the old guard without a word.
    if (sceneDelegate.includes(override)) return sceneDelegate;
    throw new Error('withCarPlay: SceneDelegate.swift was generated by another version of this plugin; run a clean prebuild (scripts/prebuild.sh)');
  }
  if (sceneDelegate.split(SCENE_DELEGATE_ANCHOR).length !== 2 || !sceneDelegate.includes('class SceneDelegate: ExpoAppSceneDelegate')) {
    throw new Error('withCarPlay: SceneDelegate.swift is not the Expo SDK 58 template this plugin extends (plugins/with-carplay.ts, withOneWindow)');
  }
  const out = sceneDelegate.replace(SCENE_DELEGATE_ANCHOR, override);
  return out.includes('import UIKit') ? out : out.replace('internal import Expo\n', 'internal import Expo\nimport UIKit\n');
}

/** The SDK 58 factory asks the same delegate for its URL with or without a window (D265). */
export function withCarPlayAppDelegate(appDelegate: string): string {
  const anchor = '  override func bundleURL() -> URL? {\n';
  const selected = '    if let url = BookClubReactStartup.bundleURL { return url } // D265\n';
  const controller = [
    '  // Deny a pending camera presentation after the scene connects (D266).',
    '  override func createRootViewController() -> UIViewController {',
    '    BookClubPhoneViewController()',
    '  }',
    '', '',
  ].join('\n');
  if (appDelegate.includes(controller + anchor + selected)) return appDelegate;
  if (appDelegate.includes(anchor + selected)) throw new Error('withCarPlay: AppDelegate.swift needs a clean prebuild');
  if (appDelegate.split(anchor).length !== 2) {
    throw new Error('withCarPlay: AppDelegate.swift is missing the SDK 58 bundleURL override');
  }
  const out = appDelegate.replace(anchor, controller + anchor + selected);
  return out.includes('import UIKit') ? out : `import UIKit\n${out}`;
}

/**
 * CarPlay (D221), only when enabled: the audio entitlement, the car's scene in the Info.plist, its
 * scene delegate (plugins/carplay/BookClubCarPlaySceneDelegate.swift) in the app target, and the
 * phone's scene delegate kept to one window (D232). The
 * templates themselves are in the BookClubNative module, in every build: with this off nothing
 * connects them.
 */
const withCarPlay: ConfigPlugin<CarPlayProps> = (config, { enabled }) => {
  if (!enabled) return config;
  config = withPodfileProperties(config, (config) => {
    // Expo's default window-only Updates handler would also claim the controller (D265).
    config.modResults.updatesCustomInit = 'true';
    return config;
  });
  config = withEntitlementsPlist(config, (config) => {
    config.modResults[CARPLAY_ENTITLEMENT] = true;
    return config;
  });
  config = withInfoPlist(config, (config) => {
    config.modResults = withCarPlayScene(config.modResults) as typeof config.modResults;
    return config;
  });
  config = withDangerousMod(config, [
    'ios',
    async (config) => {
      const webViewPackage = require.resolve('react-native-webview/package.json', { paths: [config.modRequest.projectRoot] });
      const webView = path.join(path.dirname(webViewPackage), 'apple', 'RNCWebViewImpl.m');
      if (!fs.readFileSync(webView, 'utf8').includes('BookClubCaptureObservation')) {
        throw new Error('withCarPlay: install the locked workspace dependencies with pnpm before prebuild; react-native-webview is missing the native capture gate (D266)');
      }
      const audioPackage = require.resolve('expo-audio/package.json', { paths: [config.modRequest.projectRoot] });
      const audio = path.join(path.dirname(audioPackage), 'ios', 'AudioModule.swift');
      if (!fs.readFileSync(audio, 'utf8').includes('ai.badland.books.carplay-audio-mode')) {
        throw new Error('withCarPlay: install the locked workspace dependencies with pnpm before prebuild; expo-audio is missing the native audio mode gate (D266)');
      }
      const projectName = IOSConfig.XcodeUtils.getProjectName(config.modRequest.projectRoot);
      const to = path.join(config.modRequest.platformProjectRoot, projectName, DELEGATE_FILE);
      fs.copyFileSync(path.join(config.modRequest.projectRoot, 'plugins', 'carplay', DELEGATE_FILE), to);
      const phone = path.join(config.modRequest.platformProjectRoot, projectName, 'SceneDelegate.swift');
      fs.writeFileSync(phone, withOneWindow(fs.readFileSync(phone, 'utf8')));
      const app = path.join(config.modRequest.platformProjectRoot, projectName, 'AppDelegate.swift');
      fs.writeFileSync(app, withCarPlayAppDelegate(fs.readFileSync(app, 'utf8')));
      return config;
    },
  ]);
  return withXcodeProject(config, (config) => {
    const projectName = IOSConfig.XcodeUtils.getProjectName(config.modRequest.projectRoot);
    const filepath = `${projectName}/${DELEGATE_FILE}`;
    if (!config.modResults.hasFile(filepath)) {
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({ filepath, groupName: projectName, project: config.modResults });
    }
    return config;
  });
};

export default withCarPlay;
